-- Pas de policy insert/update/delete pour anon : tout passe par le RPC ci-dessous,
-- seul chemin qui vérifie réellement le rôle côté serveur.

-- Publie une communication seulement si l'auteur est actif et a le rôle
-- gerance_psy ou seimei — vérifié côté Postgres, donc réellement infalsifiable
-- (contrairement au reste du site où les permissions ne sont que côté client).
create or replace function publier_communication(
  p_auteur_id uuid, p_sceau_hash text, p_titre text, p_contenu text, p_epingle boolean default false
)
returns psy_communications
language plpgsql
security definer
set search_path = public
as $$
declare
  v_membre psy_membres;
  v_row psy_communications;
begin
  select * into v_membre from psy_membres
    where id = p_auteur_id and sceau = p_sceau_hash and statut = 'actif';

  if v_membre.id is null then
    raise exception 'Authentification invalide.';
  end if;

  if v_membre.role not in ('gerance_psy', 'seimei') then
    raise exception 'Seule la Gérance ou la Seimei peut publier une communication.';
  end if;

  insert into psy_communications (auteur_id, auteur_nom, titre, contenu, epingle)
  values (p_auteur_id, v_membre.prenom || ' ' || v_membre.nom, p_titre, p_contenu, p_epingle)
  returning * into v_row;

  return v_row;
end;
$$;

revoke all on function publier_communication(uuid, text, text, text, boolean) from public;
grant execute on function publier_communication(uuid, text, text, text, boolean) to anon;

-- Supprime une communication (mêmes règles que la publication).
create or replace function supprimer_communication(p_id bigint, p_auteur_id uuid, p_sceau_hash text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_membre psy_membres;
begin
  select * into v_membre from psy_membres
    where id = p_auteur_id and sceau = p_sceau_hash and statut = 'actif';

  if v_membre.id is null or v_membre.role not in ('gerance_psy', 'seimei') then
    raise exception 'Action non autorisée.';
  end if;

  delete from psy_communications where id = p_id;
end;
$$;

revoke all on function supprimer_communication(bigint, uuid, text) from public;
grant execute on function supprimer_communication(bigint, uuid, text) to anon;


