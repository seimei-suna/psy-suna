-- 9. psy_activity_log — journal d'activité (rempli PAR TRIGGERS,
--    jamais par le code front : aucune ligne ne peut être "oubliée")
-- ============================================================
create table if not exists psy_activity_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),

  membre_id uuid references psy_membres(id) on delete set null,
  membre_nom text,

  action_type text not null check (action_type in
    ('test', 'evaluation', 'suivi_creation', 'suivi_statut', 'rapport_seance', 'autotest_traite')),
  target_table text not null,
  target_id bigint,
  patient_nom text,
  resume text
);

create index if not exists idx_psy_activity_membre on psy_activity_log (membre_id, created_at desc);
create index if not exists idx_psy_activity_date on psy_activity_log (created_at desc);

alter table psy_activity_log enable row level security;
drop policy if exists "anon_select_psy_activity_log" on psy_activity_log;
create policy "anon_select_psy_activity_log" on psy_activity_log for select to anon using (true);
-- Pas de policy insert pour anon : seuls les triggers (security definer
-- implicite : ils tournent avec les droits du propriétaire de la table
-- déclenchante) peuvent écrire ici.

-- --- Triggers de journalisation automatique ---

create or replace function log_psy_test() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into psy_activity_log (membre_id, membre_nom, action_type, target_table, target_id, patient_nom, resume)
  values (new.psy_id, new.psy_nom, 'test', 'psy_tests', new.id, new.patient_nom,
          initcap(replace(new.type, '_', ' ')) || ' — ' || coalesce(new.statut, ''));
  return new;
end;
$$;
drop trigger if exists trg_log_psy_test on psy_tests;
create trigger trg_log_psy_test after insert on psy_tests
  for each row execute function log_psy_test();

create or replace function log_psy_evaluation() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into psy_activity_log (membre_id, membre_nom, action_type, target_table, target_id, patient_nom, resume)
  values (new.psy_id, new.evaluateur, 'evaluation', 'psy_evaluations', new.id, new.patient_nom,
          'Entretien clinique complet — ' || coalesce(new.decision, '') || ' (' || coalesce(new.score_final::text, '?') || '/52)');
  return new;
end;
$$;
drop trigger if exists trg_log_psy_evaluation on psy_evaluations;
create trigger trg_log_psy_evaluation after insert on psy_evaluations
  for each row execute function log_psy_evaluation();

create or replace function log_psy_suivi() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    insert into psy_activity_log (membre_id, membre_nom, action_type, target_table, target_id, patient_nom, resume)
    values (new.psy_referent_id, new.psy_referent_nom, 'suivi_creation', 'psy_suivis', new.id, new.patient_nom,
            'Ouverture du suivi (' || coalesce(new.statut, 'actif') || ')');
  elsif tg_op = 'UPDATE' and new.statut is distinct from old.statut then
    insert into psy_activity_log (membre_id, membre_nom, action_type, target_table, target_id, patient_nom, resume)
    values (new.psy_referent_id, new.psy_referent_nom, 'suivi_statut', 'psy_suivis', new.id, new.patient_nom,
            'Statut du suivi : ' || old.statut || ' -> ' || new.statut);
  end if;
  return new;
end;
$$;
drop trigger if exists trg_log_psy_suivi on psy_suivis;
create trigger trg_log_psy_suivi after insert or update on psy_suivis
  for each row execute function log_psy_suivi();

create or replace function log_psy_rapport_seance() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  -- target_table/target_id pointent vers le SUIVI (pas le rapport lui-même)
  -- pour que le lien "voir" en Gérance ouvre directement la fiche de suivi.
  insert into psy_activity_log (membre_id, membre_nom, action_type, target_table, target_id, patient_nom, resume)
  values (new.psy_id, new.psy_nom, 'rapport_seance', 'psy_suivis', new.suivi_id, new.patient_nom,
          'Rapport de séance — risque : ' || coalesce(new.niveau_risque, 'aucun'));
  return new;
end;
$$;
drop trigger if exists trg_log_psy_rapport_seance on psy_rapports_seance;
create trigger trg_log_psy_rapport_seance after insert on psy_rapports_seance
  for each row execute function log_psy_rapport_seance();

create or replace function log_psy_autotest_traite() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.traite = true and (old.traite is distinct from new.traite) then
    insert into psy_activity_log (membre_id, membre_nom, action_type, target_table, target_id, patient_nom, resume)
    values (new.traite_par_id, new.traite_par, 'autotest_traite', 'psy_autotests', new.id, new.patient_nom, 'Auto-test marqué comme traité');
  end if;
  return new;
end;
$$;
drop trigger if exists trg_log_psy_autotest_traite on psy_autotests;
create trigger trg_log_psy_autotest_traite after update on psy_autotests
  for each row execute function log_psy_autotest_traite();
