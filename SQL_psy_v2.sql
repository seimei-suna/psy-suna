-- ============================================================
-- 1. psy_membres — comptes individuels des psychologues
-- ============================================================
create table if not exists psy_membres (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz default now(),

  nom text not null,
  prenom text not null,
  sceau text not null,             -- hash SHA-256 (jamais le mot de passe en clair)

  role text not null default 'psychologue'
    check (role in ('psychologue', 'gerance_psy', 'seimei')),
  categorie text not null default 'branche_psy_uniquement'
    check (categorie in ('seimei_medical_psy', 'branche_psy_uniquement')),
  statut text not null default 'en_attente'
    check (statut in ('en_attente', 'actif', 'inactif'))
);

create unique index if not exists idx_psy_membres_identite
  on psy_membres (lower(nom), lower(prenom));

alter table psy_membres enable row level security;

drop policy if exists "anon_select_psy_membres" on psy_membres;
create policy "anon_select_psy_membres" on psy_membres for select to anon using (true);
drop policy if exists "anon_insert_psy_membres" on psy_membres;
create policy "anon_insert_psy_membres" on psy_membres for insert to anon with check (true);
drop policy if exists "anon_update_psy_membres" on psy_membres;
create policy "anon_update_psy_membres" on psy_membres for update to anon using (true) with check (true);

-- Personne (même avec la clé publique) ne peut lire le sceau directement.
revoke select (sceau) on psy_membres from anon, authenticated;

-- Connexion : compare le sceau côté serveur, ne renvoie jamais sa valeur,
-- et ne renvoie rien si le compte n'est pas encore activé par la Gérance.
create or replace function verifier_sceau_psy(p_nom text, p_prenom text, p_sceau_hash text)
returns table (
  id uuid, nom text, prenom text, role text, categorie text, statut text, created_at timestamptz
)
language sql
security definer
set search_path = public
stable
as $$
  select m.id, m.nom, m.prenom, m.role, m.categorie, m.statut, m.created_at
  from psy_membres m
  where lower(m.nom) = lower(p_nom)
    and lower(m.prenom) = lower(p_prenom)
    and m.sceau = p_sceau_hash
    and m.statut = 'actif'
  limit 1;
$$;

revoke all on function verifier_sceau_psy(text, text, text) from public;
grant execute on function verifier_sceau_psy(text, text, text) to anon;


