-- 2. psy_patients — fiche patient unique (find-or-create)
-- ============================================================
create table if not exists psy_patients (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),

  nom text not null,
  grade text,
  unite text,
  age int,
  sexe text
);

create unique index if not exists idx_psy_patients_nom on psy_patients (lower(nom));

alter table psy_patients enable row level security;
drop policy if exists "anon_all_psy_patients" on psy_patients;
create policy "anon_all_psy_patients" on psy_patients for all to anon using (true) with check (true);

-- Retrouve un patient par nom (insensible à la casse) ou le crée s'il
-- n'existe pas encore, et renvoie sa fiche à jour (grade/unité/âge/sexe
-- rafraîchis si fournis). Utilisé par tests/suivis/évaluations pour ne
-- jamais dupliquer un patient.
create or replace function find_or_create_psy_patient(
  p_nom text, p_grade text default null, p_unite text default null,
  p_age int default null, p_sexe text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  select id into v_id from psy_patients where lower(nom) = lower(p_nom) limit 1;
  if v_id is null then
    insert into psy_patients (nom, grade, unite, age, sexe)
    values (p_nom, p_grade, p_unite, p_age, p_sexe)
    returning id into v_id;
  else
    update psy_patients set
      grade = coalesce(p_grade, grade),
      unite = coalesce(p_unite, unite),
      age = coalesce(p_age, age),
      sexe = coalesce(p_sexe, sexe)
    where id = v_id;
  end if;
  return v_id;
end;
$$;

revoke all on function find_or_create_psy_patient(text, text, text, int, text) from public;
grant execute on function find_or_create_psy_patient(text, text, text, int, text) to anon;


